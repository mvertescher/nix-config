const fn stretch<const N: usize>(mut segs: [Seg; N], sx: f32, sy: f32) -> [Seg; N] {
    let mut i = 0;
    while i < N {
        segs[i] = match segs[i] {
            Seg::Move(x, y) => Seg::Move(x * sx, y * sy),
            Seg::Line(x, y) => Seg::Line(x * sx, y * sy),
            Seg::Quad { cx, cy, x, y } => Seg::Quad { cx: cx * sx, cy: cy * sy, x: x * sx, y: y * sy },
            Seg::Cubic { c1x, c1y, c2x, c2y, x, y } => Seg::Cubic {
                c1x: c1x * sx, c1y: c1y * sy, c2x: c2x * sx, c2y: c2y * sy, x: x * sx, y: y * sy,
            },
        };
        i += 1;
    }
    segs
}
