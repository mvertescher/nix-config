const fn alpha_mask(b: (f32, f32, f32, f32), a: f32) -> Prim {
    fill_rect(b.0, b.1, b.2 - b.0, b.3 - b.1,
        Ink::Fixed(iced::Color { a, ..rgb(0xffffff) }))
}
macro_rules! layer {
    ($run:ident, $width:expr, $alpha:expr, $bounds:expr) => {
        // The shared profile alpha applies once to the fill/stroke union.
        Prim::Masked { prims: &[$run!($width)], mask: &[alpha_mask($bounds, $alpha)] }
    };
}
